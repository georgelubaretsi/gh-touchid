// docs/commands.md and docs/errors.md, rendered from what a gh-touchid build declares in `--help --json`: its
// `commands` (as `help` shows them), `tools` (their schemas and annotations) and `errors` (codes, exit statuses and
// meanings), so the reference cannot drift from the code. `just reference` builds a test build and runs this; `just
// test` runs it with --check against its own test build, which fails while either page is out of date.
//
//   bun scripts/reference.ts [--check] <gh-touchid>
//
//   --check   write nothing; exit 1 naming each page that differs from what the build declares
//
// The output depends only on the declarations (no version, no date), so the same sources always render the same
// pages. What the core does not declare, the adapter's own codes and JSON-RPC's numbers, is written here, with the
// file each comes from.

import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

interface JsonSchema {
  type?: string | string[];
  description?: string;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  enum?: unknown[];
  minimum?: number;
  maximum?: number;
  writeOnly?: boolean;
  [keyword: string]: unknown;
}

interface Tool {
  name: string;
  inputSchema: JsonSchema;
  outputSchema: JsonSchema;
  annotations: Record<string, unknown>;
}

interface Command {
  command: string;
  tool?: string;
  title: string;
  usage: string;
  description: string;
  example: string;
}

interface ErrorCode {
  code: string;
  exit_status: number;
  description: string;
}

interface HelpDocument {
  tools: Tool[];
  commands: Command[];
  errors: ErrorCode[];
}

const root = resolve(import.meta.dir, "..");

const header =
  "<!-- Generated by `just reference` from `gh-touchid --help --json` (scripts/reference.ts); do not edit:\n" +
  "change the declarations in Sources/GHTouchID instead. -->\n";

function fail(message: string): never {
  console.error(`reference.ts: ${message}`);
  process.exit(1);
}

/** `--help --json` of `binary`; a test build needs GH_TOUCHID_TEST_DIR, so it gets an empty folder of its own. */
function helpDocument(binary: string): HelpDocument {
  const folder = mkdtempSync(join(tmpdir(), "gh-touchid-reference-"));
  try {
    const result = Bun.spawnSync([binary, "--help", "--json"], {
      env: { ...process.env, GH_TOUCHID_TEST_DIR: folder },
      stdin: "ignore",
    });
    if (result.exitCode !== 0) {
      fail(`${binary} --help --json exited ${result.exitCode}: ${result.stderr.toString().trim()}`);
    }
    const document = JSON.parse(result.stdout.toString()) as Partial<HelpDocument>;
    if (!Array.isArray(document.tools) || !Array.isArray(document.commands) || !Array.isArray(document.errors)) {
      fail(`${binary} --help --json lists no tools, commands or errors; is it a build of these sources?`);
    }
    return document as HelpDocument;
  } finally {
    rmSync(folder, { recursive: true, force: true });
  }
}

/** `text` in lines of at most 120 characters; Markdown joins them again. */
function wrapped(text: string): string {
  const lines: string[] = [];
  let line = "";
  for (const word of text.split(" ")) {
    if (line !== "" && line.length + 1 + word.length > 120) {
      lines.push(line);
      line = "";
    }
    line = line === "" ? word : `${line} ${word}`;
  }
  if (line !== "") {
    lines.push(line);
  }
  return lines.join("\n");
}

/** Declared prose as Markdown: a `<` outside code spans would open an HTML tag, which hides `<owner>`. */
function prose(text: string): string {
  return text
    .split(/(`[^`]*`)/)
    .map((part, index) => (index % 2 === 0 ? part.replaceAll("<", "&lt;") : part))
    .join("");
}

/** Declared prose safe in a table cell: GitHub's tables end a cell at any `|`, even in a code span. */
function cell(text: string): string {
  return prose(text).replaceAll("|", "\\|");
}

/** A schema's type in words: `string`, `integer or null`, `array of string`, one of `get`, `store`. */
function typeOf(schema: JsonSchema): string {
  if (Array.isArray(schema.enum)) {
    return `one of ${schema.enum.map((value) => `\`${JSON.stringify(value)}\``).join(", ")}`;
  }
  const types = (Array.isArray(schema.type) ? schema.type : [schema.type ?? "any"]).map((type) =>
    type === "array" && schema.items ? `array of ${typeOf(schema.items)}` : type,
  );
  let words = types.join(" or ");
  if (schema.minimum !== undefined && schema.maximum !== undefined) {
    words += `, ${schema.minimum} to ${schema.maximum}`;
  } else if (schema.minimum !== undefined) {
    words += `, at least ${schema.minimum}`;
  } else if (schema.maximum !== undefined) {
    words += `, at most ${schema.maximum}`;
  }
  return words;
}

/** Whether a field holds fields of its own: an object, or an array of objects. */
function nested(schema: JsonSchema): boolean {
  return schema.properties !== undefined || (schema.items !== undefined && nested(schema.items));
}

function inputTable(schema: JsonSchema): string {
  const fields = Object.entries(schema.properties ?? {});
  if (fields.length === 0) {
    return "Input: none.\n";
  }
  const required = new Set(schema.required ?? []);
  const rows = fields.map(([name, field]) => {
    const description = field.writeOnly
      ? `${field.description ?? ""} Secret: read from stdin only.`.trim()
      : (field.description ?? "");
    return `| \`${name}\` | ${cell(typeOf(field))} | ${required.has(name) ? "yes" : "no"} | ${cell(description)} |`;
  });
  return ["| Input | Type | Required | Description |", "| --- | --- | --- | --- |", ...rows, ""].join("\n");
}

function outputTable(schema: JsonSchema): string {
  const fields = Object.entries(schema.properties ?? {});
  if (fields.length === 0) {
    return "Output: an empty object.\n";
  }
  const rows = fields.map(([name, field]) => {
    const description = field.writeOnly ? `${field.description ?? ""} Secret.`.trim() : (field.description ?? "");
    return `| \`${name}\` | ${cell(typeOf(field))} | ${cell(description)} |`;
  });
  let table = ["| Output | Type | Description |", "| --- | --- | --- |", ...rows, ""].join("\n");
  const inner = Object.fromEntries(fields.filter(([, field]) => nested(field)));
  if (Object.keys(inner).length > 0) {
    table +=
      "\n<details>\n<summary>The fields within " +
      Object.keys(inner)
        .map((name) => `<code>${name}</code>`)
        .join(", ") +
      " (JSON Schema)</summary>\n\n```json\n" +
      JSON.stringify(inner, null, 2) +
      "\n```\n\n</details>\n";
  }
  return table;
}

function annotations(tool: Tool): string {
  const hint = (key: string) => (tool.annotations[key] === true ? "yes" : "no");
  return (
    `Annotations: read-only ${hint("readOnlyHint")} · destructive ${hint("destructiveHint")} · ` +
    `idempotent ${hint("idempotentHint")} · open-world ${hint("openWorldHint")}.\n`
  );
}

function commandsPage(document: HelpDocument): string {
  const tools = new Map(document.tools.map((tool) => [tool.name, tool]));
  const parts = [
    header,
    "# Commands\n",
    wrapped(
      "`gh-touchid help` lists every command; `gh-touchid help <command>` or `gh-touchid <command> --help` shows " +
        "one, with an example. Everything after `gh-touchid gh` goes to GitHub CLI, so `gh-touchid gh --help` is " +
        "GitHub CLI's help.",
    ) + "\n",
    wrapped(
      "Each command takes its input as flags and arguments, or with `--input <file|->` as one JSON object; " +
        "`rpc` and `mcp` take the same object as a call's arguments. The Input tables name its keys: on the command " +
        "line a key is the flag of the same name in kebab case (`client_id` is `--client-id`; `open_browser` false " +
        "is `--no-open`), or the argument the usage shows in its place. With `--json` the output is one JSON object, " +
        "which the Output tables describe; a failure ends stderr with an [error code](errors.md). The " +
        "annotations are MCP's tool hints. See [Scripts and agents](scripting.md) for `--json`, `--input`, `rpc` " +
        "and `mcp`.",
    ) + "\n",
    "| Usage | What it does |\n| --- | --- |\n" +
      document.commands
        // GitHub's anchor for a heading of plain words: `app create` is `#app-create`
        .map((command) => {
          const anchor = command.command.replaceAll(" ", "-");
          return `| [\`${command.usage.replaceAll("|", "\\|")}\`](#${anchor}) | ${cell(command.title)} |`;
        })
        .join("\n") +
      "\n",
  ];
  for (const command of document.commands) {
    const section = [
      `## ${command.command}\n`,
      "```sh\n" + command.usage + "\n```\n",
      wrapped(prose(command.description)) + "\n",
      "Example:\n\n```sh\n" + command.example + "\n```\n",
    ];
    const tool = command.tool === undefined ? undefined : tools.get(command.tool);
    if (command.tool !== undefined && tool === undefined) {
      fail(`${command.command} names the tool ${command.tool}, which --help --json does not list`);
    }
    if (tool) {
      section.push(inputTable(tool.inputSchema), outputTable(tool.outputSchema), annotations(tool));
    }
    parts.push(section.join("\n"));
  }
  return parts.join("\n");
}

function errorsPage(document: HelpDocument): string {
  const rows = document.errors.map(
    (error) => `| \`${error.code}\` | ${error.exit_status} | ${cell(error.description)} |`,
  );
  return [
    header,
    "# Error codes\n",
    wrapped(
      "Every failure carries a stable code, in snake case. With `--json`, the last line gh-touchid writes to stderr " +
        'is `{"error": {"code": "…", "message": "…"}}`; `rpc` puts the code in the error\'s `data.code` (with the ' +
        'message in `data.message`), and `mcp` returns a tool error whose text is that same object, also under ' +
        '`_meta["gh-touchid/error"]`. The message says what to run next; match on the code, not the message.',
    ) + "\n",
    wrapped(
      "Exit status 2 means the input was wrong, so running the same thing again cannot help; 1 is any other " +
        "failure, and 0 success. `gh` and `as` exit with the status of the program they ran; with `--json` they " +
        "exit 0 and the output's `exit_code` holds it.",
    ) + "\n",
    ["| Code | Exit status | Meaning |", "| --- | --- | --- |", ...rows, ""].join("\n"),
    "## The adapter's own codes\n",
    wrapped(
      "`rpc` and `mcp` run through gh-touchid-adapter, which reports the core's codes as they are and adds two of " +
        "its own ([CoreCall.swift](../Sources/GHTouchIDAdapter/CoreCall.swift), " +
        "[Catalog.swift](../Sources/GHTouchIDAdapter/Catalog.swift)):",
    ) + "\n",
    [
      "| Code | Meaning |",
      "| --- | --- |",
      "| `adapter` | The adapter could not run gh-touchid, or gh-touchid said nothing it could read; check that " +
        "gh-touchid runs (`gh-touchid --help --json`). |",
      "| `secret_needs_stdin` | The tool takes a secret, which only standard input may carry; run the command the " +
        "message names in a terminal, with the secret piped in. |",
      "",
    ].join("\n"),
    "## JSON-RPC error numbers\n",
    wrapped(
      "`rpc` answers a failed request with a JSON-RPC 2.0 error whose `code` is one of these numbers, and whose " +
        "`data` is `{\"code\", \"message\"}`: gh-touchid's or the adapter's code, or for a request the adapter " +
        "refuses itself, one of its own ([RPCServer.swift](../Sources/GHTouchIDAdapter/RPCServer.swift)).",
    ) + "\n",
    [
      "| Number | `data.code` | When |",
      "| --- | --- | --- |",
      "| -32700 | `parse_error` | A line that is not JSON; the server reads on. |",
      "| -32600 | `invalid_request` | A message that is not a JSON-RPC request, or reuses the id of a call still " +
        "running. |",
      "| -32601 | `method_not_found` | A method that names no operation. |",
      "| -32602 | `invalid_params` | Params that are not a JSON object. |",
      "| -32602 | gh-touchid's | gh-touchid refused the input (exit status 2). |",
      "| -32000 | gh-touchid's, or `secret_needs_stdin` | Any other failure of gh-touchid, and the adapter's refusal " +
        "of a secret. |",
      "| -32603 | `adapter` | gh-touchid could not run, or said nothing the adapter could read. |",
      "| -32800 | `cancelled` | The client cancelled the request (as in LSP). |",
      "",
    ].join("\n"),
  ].join("\n");
}

const args = process.argv.slice(2);
const check = args[0] === "--check";
const binary = check ? args[1] : args[0];
if (binary === undefined || args.length !== (check ? 2 : 1)) {
  fail("usage: bun scripts/reference.ts [--check] <gh-touchid>");
}
const document = helpDocument(binary);
const pages: [string, string][] = [
  ["docs/commands.md", commandsPage(document)],
  ["docs/errors.md", errorsPage(document)],
];
if (check) {
  const stale = pages.filter(([path, text]) => {
    try {
      return readFileSync(join(root, path), "utf8") !== text;
    } catch {
      return true;
    }
  });
  for (const [path] of stale) {
    console.error(`reference.ts: ${path} is not what ${binary} declares; run \`just reference\` and commit it`);
  }
  process.exit(stale.length === 0 ? 0 : 1);
}
for (const [path, text] of pages) {
  writeFileSync(join(root, path), text);
}
